const getSeoBlock = (categorySlug, cityName) => {
  let catBlock = null;
  if (categorySlug) {
    const slug = String(categorySlug).toLowerCase();
    for (const [key, val] of Object.entries(CATEGORY_SEO)) {
      if (slug === key || slug.startsWith(key)) {
        catBlock = val;
        break;
      }
    }
  }

  let cityBlock = null;
  if (cityName) {
    cityBlock = CITY_SEO[cityName] || null;
  }

  return {
    category: catBlock,
    city: cityBlock
  };
};

const getFaqSchema = (categorySlug, baseUrl = 'https://cypilan.com') => {
  if (!categorySlug) return null;
  const slug = String(categorySlug).toLowerCase();
  let block = null;
  for (const [key, val] of Object.entries(CATEGORY_SEO)) {
    if (slug === key || slug.startsWith(key)) {
      block = val;
      break;
    }
  }

  if (!block || !block.faqs || block.faqs.length === 0) return null;

  return {
    "@type": "FAQPage",
    "@id": `${baseUrl}/listings?category=${categorySlug}#faq`,
    "mainEntity": block.faqs.map(faq => ({
      "@type": "Question",
      "name": faq.q,
      "acceptedAnswer": {
        "@type": "Answer",
        "text": faq.a
      }
    }))
  };
};

